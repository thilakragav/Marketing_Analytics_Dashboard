    for k, v in KPI_DEFINITIONS.items():
        rows.append({
            "KPI": v["name"],
            "Definition": v["definition"],
            "Formula": v["formula"],
            "Source System": v["source_system"],
            "Source Table": v["source_table"],
            "Source Field": v["source_field"],
            "Aggregation": v["aggregation"],
            "Currency / Unit": v["currency"],
            "Attribution Basis": v["attribution_basis"],
            "Refresh Cadence": v["refresh_cadence"]
        })
    return pd.DataFrame(rows)
