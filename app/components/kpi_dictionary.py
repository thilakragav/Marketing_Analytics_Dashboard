def get_kpi_def(kpi_key: str):
    """Retrieve definition dictionary for a given KPI, or fallback to sensible default."""
    for key, val in KPI_DEFINITIONS.items():
        if key.lower() in kpi_key.lower() or kpi_key.lower() in key.lower():
            return val
    return {
        "name": kpi_key,
        "definition": "Standard marketing performance metric.",
        "formula": "Calculated from aggregated dataset",
        "source_system": "Marketing Database",
        "source_table": "paid_media_daily / campaign_performance",
        "source_field": "Not available in current dataset.",
        "aggregation": "SUM or AVG",
        "scope": "Current selection",
        "currency": "Standard",
        "attribution_basis": "Last Click",
        "exclusions": "None",
        "refresh_cadence": "Daily",
        "format": "standard"
    }

def render_kpi_popover(kpi_key: str):
    """Renders a small info icon popover displaying official KPI dictionary metadata."""
    meta = get_kpi_def(kpi_key)
    with st.popover("ℹ️", use_container_width=False):
        st.markdown(f"### 📖 {meta['name']}")
        st.markdown(f"**Definition:** {meta['definition']}")
        st.divider()
        col1, col2 = st.columns(2)
        with col1:
            st.markdown(f"**Formula:** `{meta['formula']}`")
            st.markdown(f"**Source System:** {meta['source_system']}")
            st.markdown(f"**Source Table:** `{meta['source_table']}`")
            st.markdown(f"**Source Field:** `{meta['source_field']}`")
        with col2:
            st.markdown(f"**Aggregation:** `{meta['aggregation']}`")
            st.markdown(f"**Scope:** {meta['scope']}")
            st.markdown(f"**Currency / Unit:** {meta['currency']}")
            st.markdown(f"**Attribution Basis:** {meta['attribution_basis']}")
        st.caption(f"Exclusions: {meta['exclusions']} | Refresh: {meta['refresh_cadence']}")

def get_dictionary_dataframe():
    """Returns a pandas DataFrame representation of the KPI dictionary for table display."""
